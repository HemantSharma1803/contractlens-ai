import { ContractIntelligence, StandardClauseCategory, ClausePresence } from '../types/contract';
import { STANDARD_CLAUSE_CATEGORIES } from '../services/contractIntelligenceService';

function buildClausePresences(
  contractId: string,
  docName: string,
  presentItems: Record<string, { page: number; section: string; snippet: string; summary?: string }>
): ClausePresence[] {
  return STANDARD_CLAUSE_CATEGORIES.map((category) => {
    const found = presentItems[category];
    if (found) {
      return {
        category,
        status: 'present',
        sectionIdentifier: found.section,
        pageNumber: found.page,
        snippet: found.snippet,
        confidence: 'HIGH',
        confidenceScore: 0.96,
        summary: found.summary,
        sourceReferences: [
          {
            id: `ev-clause-${category.toLowerCase().replace(/[\s&/]+/g, '-')}-${contractId}`,
            documentId: contractId,
            documentName: docName,
            pageNumber: found.page,
            sectionIdentifier: found.section,
            textSnippet: found.snippet,
            confidenceScore: 0.96,
            verifiedByHuman: true,
          },
        ],
      };
    }
    return {
      category,
      status: 'not_identified',
      confidence: 'REVIEW',
      confidenceScore: 0.25,
      sourceReferences: [],
    };
  });
}

